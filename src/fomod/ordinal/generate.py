#!/usr/bin/env python3
"""Generate production ordinal uppercase data from the retained official UCD.

No tests, application probes, game roots or mod roots are involved. Writes only
the production table and provenance beside this file.
"""
from pathlib import Path
import hashlib
import json

DIRECTORY = Path(__file__).resolve().parent
SOURCE = DIRECTORY.parent.parent / "maintenance/casing/UnicodeData-15.0.0.txt"
EXPECTED_SHA = "806e9aed65037197f1ec85e12be6e8cd870fc5608b4de0fffd990f689f376a73"
ALGORITHM = "dotnet9-icu-ordinal-simple-upper-ucd15-v1"


def generate():
    if SOURCE.stat().st_size > 4 * 1024 * 1024:
        raise ValueError("UCD exceeds source budget")
    source = SOURCE.read_bytes()
    if hashlib.sha256(source).hexdigest() != EXPECTED_SHA:
        raise ValueError("Retained UCD digest differs")
    pairs = []
    previous = -1
    for line in source.decode("utf-8").splitlines():
        fields = line.split(";")
        if len(fields) != 15:
            raise ValueError("Unexpected UCD row width")
        codepoint = int(fields[0], 16)
        if not previous < codepoint <= 0x10FFFF:
            raise ValueError("UCD source ordering differs")
        previous = codepoint
        if fields[12] and codepoint not in (0x0131, 0x017F):
            destination = int(fields[12], 16)
            if (not 0 <= destination <= 0x10FFFF
                    or 0xD800 <= codepoint <= 0xDFFF
                    or 0xD800 <= destination <= 0xDFFF
                    or (codepoint <= 0xFFFF) != (destination <= 0xFFFF)):
                raise ValueError("Ordinal mapping changes scalar or UTF16 width")
            if destination != codepoint:
                pairs.append((codepoint, destination))
    canonical = (ALGORITHM + "\n15.0.0\n0131=0131\n017F=017F\n").encode("ascii")
    canonical += "".join(f"{a:06X}:{b:06X}\n" for a, b in pairs).encode("ascii")
    table_hash = hashlib.sha256(canonical).hexdigest()
    output = [
        "// Generated by ordinal/generate.py; do not edit pairs manually.",
        "// Source/license retained in maintenance/casing/; see provenance.json.",
        "pub(super) const UPPERCASE: &[(u32, u32)] = &[",
        *[f"    (0x{a:X}, 0x{b:X})," for a, b in pairs],
        "];", "",
    ]
    (DIRECTORY / "data.rs").write_text("\n".join(output), encoding="utf-8", newline="\n")
    provenance = {
        "algorithm": ALGORITHM,
        "unicodeVersion": "15.0.0",
        "source": "../../maintenance/casing/UnicodeData-15.0.0.txt",
        "sourceUrl": "https://www.unicode.org/Public/15.0.0/ucd/UnicodeData.txt",
        "sourceSha256": EXPECTED_SHA,
        "license": "../../maintenance/casing/LICENSE.txt",
        "licenseSha256": hashlib.sha256((SOURCE.parent / "LICENSE.txt").read_bytes()).hexdigest(),
        "mappingFieldZeroBased": 12,
        "ordinalExceptions": ["U+0131", "U+017F"],
        "mappingPairCount": len(pairs),
        "tableSha256": table_hash,
        "tableDigestEncoding": "ASCII algorithm LF version LF 0131=0131 LF 017F=017F LF; sorted uppercase six-digit source:destination hex lines with LF",
        "referenceBmp": "https://github.com/dotnet/runtime/blob/v9.0.0/src/native/libs/System.Globalization.Native/pal_common.c",
        "referenceSupplementary": "https://github.com/dotnet/runtime/blob/v9.0.0/src/libraries/System.Private.CoreLib/src/System/Globalization/OrdinalCasing.Icu.cs",
    }
    (DIRECTORY / "provenance.json").write_text(json.dumps(provenance, indent=2) + "\n", encoding="utf-8", newline="\n")
    print(f"Generated {len(pairs)} ordinal mappings; table SHA256 {table_hash}")


if __name__ == "__main__":
    generate()
