#!/usr/bin/env python3
"""Generate production .NET char punctuation ranges from retained Unicode 15.

Reads the existing pinned UCD and license; writes only this module's production
table/provenance. This generator does not open game, mod or test trees.
"""
from pathlib import Path
import hashlib
import json

DIRECTORY = Path(__file__).resolve().parent
SOURCE_DIRECTORY = DIRECTORY.parent / "maintenance" / "casing"
SOURCE_HASH = "806e9aed65037197f1ec85e12be6e8cd870fc5608b4de0fffd990f689f376a73"
CATEGORIES = set("Lu Ll Lt Lm Lo Mn Mc Me Nd Nl No Pc Pd Ps Pe Pi Pf Po Sm Sc Sk So Zs Zl Zp Cc Cf Cs Co Cn".split())
PUNCTUATION = {"Pc", "Pd", "Ps", "Pe", "Pi", "Pf", "Po"}
ALGORITHM = "dotnet-char-punctuation-bmp-v1"


def require(condition, message):
    if not condition:
        raise ValueError(message)


def generate():
    source_path = SOURCE_DIRECTORY / "UnicodeData-15.0.0.txt"
    require(source_path.stat().st_size <= 4 * 1024 * 1024, "UCD exceeds source budget")
    source = source_path.read_bytes()
    require(hashlib.sha256(source).hexdigest() == SOURCE_HASH, "Pinned UCD digest differs")
    ranges = []
    previous = -1
    pending = None
    for line in source.decode("utf-8").splitlines():
        fields = line.split(";")
        require(len(fields) == 15, "UCD field count differs")
        codepoint = int(fields[0], 16)
        name, category = fields[1:3]
        require(previous < codepoint <= 0x10FFFF, "UCD codepoint order differs")
        require(category in CATEGORIES, "Unknown UCD category")
        previous = codepoint
        if name.endswith(", First>"):
            require(pending is None, "Nested UCD range")
            pending = (codepoint, name[:-8], category)
            continue
        if name.endswith(", Last>"):
            require(pending is not None, "Unmatched UCD range")
            first, range_name, range_category = pending
            require(first < codepoint and range_name == name[:-7] and category == range_category,
                    "UCD range endpoints differ")
            pending = None
        else:
            require(pending is None, "Interrupted UCD range")
            first = codepoint
        if category not in PUNCTUATION or first > 0xFFFF:
            continue
        last = min(codepoint, 0xFFFF)
        require(not (first <= 0xDFFF and last >= 0xD800), "Punctuation contains surrogates")
        if ranges and first == ranges[-1][1] + 1:
            ranges[-1] = (ranges[-1][0], last)
        else:
            require(not ranges or first > ranges[-1][1], "Punctuation ranges overlap")
            ranges.append((first, last))
    require(pending is None, "Unterminated UCD range")
    canonical = f"{ALGORITHM}\n15.0.0\n" + "".join(f"P:{a:04X}:{b:04X}\n" for a, b in ranges)
    table_hash = hashlib.sha256(canonical.encode("ascii")).hexdigest()
    lines = [
        "// Generated by unicode_case/generate_punctuation.py from retained Unicode 15.0.",
        "// Source/license: maintenance/casing/UnicodeData-15.0.0.txt and LICENSE.txt.",
        "pub(super) const BMP_PUNCTUATION: &[(u32, u32)] = &[",
        *[f"    (0x{a:X}, 0x{b:X})," for a, b in ranges],
        "];", "",
    ]
    (DIRECTORY / "punctuation.rs").write_text("\n".join(lines), encoding="utf-8", newline="\n")
    provenance = {
        "algorithm": ALGORITHM,
        "unicodeVersion": "15.0.0",
        "source": "../maintenance/casing/UnicodeData-15.0.0.txt",
        "sourceSha256": SOURCE_HASH,
        "license": "../maintenance/casing/LICENSE.txt",
        "licenseSha256": hashlib.sha256((SOURCE_DIRECTORY / "LICENSE.txt").read_bytes()).hexdigest(),
        "categories": sorted(PUNCTUATION),
        "rangeCount": len(ranges),
        "codeUnitCount": sum(b - a + 1 for a, b in ranges),
        "tableSha256": table_hash,
        "tableDigestEncoding": "ASCII algorithm LF version LF; sorted P:first:last uppercase four-digit hex lines with LF",
        "generator": "generate_punctuation.py",
        "generatorSha256": hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
    }
    (DIRECTORY / "punctuation-provenance.json").write_text(json.dumps(provenance, indent=2) + "\n", encoding="utf-8", newline="\n")
    print(json.dumps(provenance, indent=2))


if __name__ == "__main__":
    generate()
