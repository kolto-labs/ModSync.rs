#!/usr/bin/env python3
"""Generate production casing data from the retained official Unicode 15.0 UCD.

This is a data generator, not a filesystem maintenance or test harness. It reads
only its pinned source and license and writes data.rs and provenance.json beside
this script. No game or mod tree is opened. Run from any working directory.
"""
from pathlib import Path
import hashlib
import json

DIRECTORY = Path(__file__).resolve().parent
SOURCE = DIRECTORY / "UnicodeData-15.0.0.txt"
EXPECTED_SOURCE_SHA256 = "806e9aed65037197f1ec85e12be6e8cd870fc5608b4de0fffd990f689f376a73"
ALGORITHM = "dotnet-icu-invariant-simple-lower-v1"
UNICODE_VERSION = "15.0.0"


def require(condition, message):
    if not condition:
        raise ValueError(message)


def scalar(value):
    return 0 <= value <= 0x10FFFF and not 0xD800 <= value <= 0xDFFF


def generate():
    require(SOURCE.stat().st_size <= 4 * 1024 * 1024, "UCD exceeds source budget")
    source = SOURCE.read_bytes()
    source_hash = hashlib.sha256(source).hexdigest()
    require(source_hash == EXPECTED_SOURCE_SHA256, "Official UCD source digest differs")
    assigned = []
    mappings = []
    pending = None
    previous = -1
    for line_number, line in enumerate(source.decode("utf-8").splitlines(), 1):
        fields = line.split(";")
        require(len(fields) == 15, f"UCD field count at line {line_number}")
        codepoint = int(fields[0], 16)
        require(previous < codepoint <= 0x10FFFF, "UCD codepoints must be unique and sorted")
        previous = codepoint
        name, category = fields[1], fields[2]
        if name.endswith(", First>"):
            require(pending is None, "Nested UCD range")
            require(not fields[13], "Range cannot contain a lowercase mapping")
            pending = (codepoint, name[:-8], category)
            continue
        if name.endswith(", Last>"):
            require(pending is not None, "Unmatched UCD range endpoint")
            first, range_name, range_category = pending
            require(range_name == name[:-7] and range_category == category and first < codepoint,
                    "UCD range endpoints disagree")
            require(not fields[13], "Range cannot contain a lowercase mapping")
            if category not in ("Cn", "Cs"):
                require(scalar(first) and scalar(codepoint), "Assigned range contains invalid scalar")
                assigned.append((first, codepoint))
            pending = None
            continue
        require(pending is None, "UCD range interrupted by an ordinary row")
        if category not in ("Cn", "Cs"):
            require(scalar(codepoint), "Assigned codepoint is not a scalar")
            assigned.append((codepoint, codepoint))
        if fields[13]:
            destination = int(fields[13], 16)
            require(scalar(codepoint) and scalar(destination), "Lowercase mapping is not scalar")
            require((codepoint <= 0xFFFF) == (destination <= 0xFFFF),
                    "Lowercase mapping changes UTF16 width")
            # .NET ChangeCaseInvariant deliberately preserves U+0130.
            if codepoint != 0x0130 and destination != codepoint:
                mappings.append((codepoint, destination))
    require(pending is None, "Unterminated UCD range")
    ranges = []
    for first, last in assigned:
        if ranges and first == ranges[-1][1] + 1:
            ranges[-1] = (ranges[-1][0], last)
        else:
            require(not ranges or first > ranges[-1][1], "Assigned ranges overlap")
            ranges.append((first, last))
    # This digest binds both operation mapping and assigned-scalar admission.
    canonical = bytearray(f"{ALGORITHM}\n{UNICODE_VERSION}\n0130=0130\n".encode("ascii"))
    for first, last in ranges:
        canonical.extend(f"A:{first:06X}:{last:06X}\n".encode("ascii"))
    for source_cp, destination in mappings:
        canonical.extend(f"M:{source_cp:06X}:{destination:06X}\n".encode("ascii"))
    table_hash = hashlib.sha256(canonical).hexdigest()
    lines = [
        "// Generated by casing/generate.py from official UnicodeData-15.0.0.txt.",
        "// Unicode data license: casing/LICENSE.txt. Do not edit pairs manually.",
        f'pub(super) const ALGORITHM: &str = "{ALGORITHM}";',
        f'pub(super) const UNICODE_VERSION: &str = "{UNICODE_VERSION}";',
        "pub(super) const SOURCE_SHA256: &str =",
        f'    "{source_hash}";',
        "pub(super) const TABLE_SHA256: &str =",
        f'    "{table_hash}";',
        "pub(super) const ASSIGNED: &[(u32, u32)] = &[",
        *[f"    (0x{first:X}, 0x{last:X})," for first, last in ranges],
        "];",
        "pub(super) const LOWERCASE: &[(u32, u32)] = &[",
        *[f"    (0x{source_cp:X}, 0x{destination:X})," for source_cp, destination in mappings],
        "];",
        "",
    ]
    (DIRECTORY / "data.rs").write_text("\n".join(lines), encoding="utf-8", newline="\n")
    provenance = {
        "algorithm": ALGORITHM,
        "unicodeVersion": UNICODE_VERSION,
        "sourceUrl": "https://www.unicode.org/Public/15.0.0/ucd/UnicodeData.txt",
        "sourceSha256": source_hash,
        "tableSha256": table_hash,
        "licenseUrl": "https://www.unicode.org/license.txt",
        "licenseSha256": hashlib.sha256((DIRECTORY / "LICENSE.txt").read_bytes()).hexdigest(),
        "mappingFieldZeroBased": 13,
        "invariantLowercaseExceptions": ["U+0130"],
        "assignedRangeCount": len(ranges),
        "assignedScalarCount": sum(last - first + 1 for first, last in ranges),
        "mappingPairCount": len(mappings),
        "tableDigestEncoding": "ASCII algorithm LF version LF 0130=0130 LF; sorted A:first:last and M:source:destination lines with uppercase six-digit hex and LF",
        "generator": "generate.py",
    }
    (DIRECTORY / "provenance.json").write_text(json.dumps(provenance, indent=2) + "\n", encoding="utf-8", newline="\n")
    print(json.dumps(provenance, indent=2))


if __name__ == "__main__":
    generate()
